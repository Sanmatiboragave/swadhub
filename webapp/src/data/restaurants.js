function hash(str) {
  let h = 0
  for (let i = 0; i < str.length; i++) h = (h * 31 + str.charCodeAt(i)) >>> 0
  return h
}

const cuisineByKey = Object.fromEntries(CUISINES.map((c) => [c.key, c]))

function buildMenu(cuisineKey, restaurantId) {
  const cuisine = cuisineByKey[cuisineKey]
  return cuisine.menu.map((row, i) => {
    const [name, desc, price, img, popular, veg] = row
    return {
      id: `${restaurantId}-d${i + 1}`,
      name,
      desc,
      price,
      img,
      popular: Boolean(popular),
      veg: Boolean(veg),
    }
  })
}

const OFFERS = [
  '20% OFF up to ₹80',
  'Free delivery',
  '50% OFF up to ₹120',
  'Buy 1 Get 1 on drinks',
  '₹100 OFF above ₹499',
  '15% OFF first order',
  'Flat ₹50 OFF',
  'Free filter coffee',
]

function buildRestaurants() {
  const list = []
  for (const cuisine of CUISINES) {
    cuisine.names.forEach((name, i) => {
      areas.forEach((area, a) => {
        const id = `blr-${cuisine.key}-${i}-${a}`
        const seed = hash(id)
        const rating = Math.round((4.1 + (seed % 9) / 10) * 10) / 10
        const reviews = 80 + (seed % 6200)
        const etaMin = 16 + (seed % 32)
        const fee = seed % 5 === 0 ? 0 : 19 + (seed % 3) * 10
        const km = ((seed % 55) / 10 + 0.4).toFixed(1)
        list.push({
          id,
          name: `${name} — ${area}`,
          area,
          city: 'Bengaluru',
          cuisine: cuisine.cuisine,
          cuisineKey: cuisine.key,
          categories: cuisine.categories,
          rating,
          reviews,
          eta: `${etaMin}–${etaMin + 10} min`,
          etaMin,
          fee,
          distance: `${km} km`,
          offer: OFFERS[seed % OFFERS.length],
          tags: seed % 2 === 0 ? ['Bengaluru favourite'] : ['Cloud kitchen'],
          img: cuisine.img,
          hero: cuisine.hero,
          color: cuisine.color,
        })
      })
    })
  }
  return list.sort((a, b) => b.rating - a.rating || a.area.localeCompare(b.area))
}

const restaurants = buildRestaurants()

export function dishesMatch(restaurant, query) {
  const cuisine = cuisineByKey[restaurant.cuisineKey]
  if (!cuisine) return false
  return cuisine.menu.some((row) => String(row[0]).toLowerCase().includes(query))
}

export function getRestaurant(id) {
  const r = restaurants.find((x) => x.id === id)
  if (!r) return null
  return { ...r, menu: buildMenu(r.cuisineKey, r.id) }
}

export default restaurants
